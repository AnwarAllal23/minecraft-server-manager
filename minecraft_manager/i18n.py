from __future__ import annotations

from typing import Dict

# The app is written with French as its source language: every tr() call
# below is keyed by the original French string, exactly like Qt's own
# tr()/QObject::tr() convention keys off the source-language text instead of
# an artificial identifier. "fr" therefore has no dictionary of its own -
# tr() just returns the key unchanged when the current language is French or
# when a translation is missing, so the app never shows a blank string.

LANGUAGES: Dict[str, str] = {
    "en": "English",
    "fr": "Français",
    "es": "Español",
}

_current_language = "en"


def set_language(language: str) -> None:
    global _current_language
    _current_language = language if language in LANGUAGES else "en"


def get_language() -> str:
    return _current_language


def tr(text: str, **kwargs) -> str:
    """Translate ``text`` (a French source string) to the current language.

    Placeholders use str.format() syntax, e.g. tr("Statut: {state}").format(state=...)
    is the call site's job; tr() itself only does the dict lookup so callers
    can still pass kwargs straight through when convenient.
    """
    table = _TRANSLATIONS.get(_current_language)
    translated = table.get(text, text) if table else text
    if kwargs:
        try:
            return translated.format(**kwargs)
        except (KeyError, IndexError):
            return translated
    return translated


